export const isEnglish = () => window.location.pathname === '/en' || window.location.pathname.startsWith('/en/');

export function translate(value) {
  return isEnglish() ? english[value] || value : value;
}

function translateDynamic(value) {
  let match = value.match(/^Tüm (\d+) tehdit etkisiz hale getirildi\. UMAY bağlantısı güvenli şekilde sonlandırılıyor\.$/);
  if (match) return `All ${match[1]} threats have been neutralized. The UMAY link is shutting down securely.`;

  match = value.match(/^(\d+)\/(\d+) tehdit indirildi\. UAV taramasını daha sık kullan, köşelere körlemesine girme\.$/);
  if (match) {
    return `${match[1]}/${match[2]} threats neutralized. Use the UAV scan more often and do not enter corners blindly.`;
  }

  return value;
}

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const original = node.nodeValue;
    const normalized = original.replace(/\s+/g, ' ').trim();
    if (!normalized) return;
    const translated = english[normalized] || translateDynamic(normalized);
    if (translated === normalized) return;
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    node.nodeValue = `${leading}${translated}${trailing}`;
    return;
  }

  if (!(node instanceof Element)) return;
  ['aria-label', 'alt', 'title', 'placeholder'].forEach((attribute) => {
    const value = node.getAttribute(attribute);
    if (value && english[value]) node.setAttribute(attribute, english[value]);
  });
}

function walk(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  translateNode(root);
  while (walker.nextNode()) translateNode(walker.currentNode);
}

function languagePath() {
  const { pathname, search, hash } = window.location;
  const target = isEnglish()
    ? pathname.replace(/^\/en(?=\/|$)/, '') || '/'
    : `/en${pathname === '/' ? '/' : pathname}`;
  return `${target}${search}${hash}`;
}

function localizeLinks(root) {
  if (!isEnglish()) return;
  root.querySelectorAll?.('a[href^="/"]').forEach((link) => {
    const href = link.getAttribute('href');
    if (
      !href ||
      link.classList.contains('language-switch') ||
      link.classList.contains('language-switch-mobile') ||
      href.startsWith('/en/') ||
      href.startsWith('/images/') ||
      href.startsWith('/src/')
    ) {
      return;
    }
    link.setAttribute('href', `/en${href}`);
  });
}

export function initI18n() {
  document.documentElement.lang = isEnglish() ? 'en' : 'tr';

  const header = document.querySelector('.site-header');
  if (header && !header.querySelector('.language-switch')) {
    const switcher = document.createElement('a');
    switcher.className = 'language-switch';
    switcher.href = languagePath();
    switcher.textContent = isEnglish() ? 'TR' : 'EN';
    switcher.setAttribute('aria-label', isEnglish() ? 'Türkçe sürüme geç' : 'Switch to English');
    header.insertBefore(switcher, header.querySelector('.hamburger'));
  }

  const mobileList = document.querySelector('.mobile-menu ul');
  if (mobileList && !mobileList.querySelector('.language-switch-mobile')) {
    const item = document.createElement('li');
    item.innerHTML = `<a class="mobile-nav-link language-switch-mobile" href="${languagePath()}">${isEnglish() ? 'TR' : 'EN'}</a>`;
    mobileList.appendChild(item);
  }

  if (isEnglish()) {
    walk(document.body);
    localizeLinks(document);
    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === 'characterData') translateNode(mutation.target);
        mutation.addedNodes.forEach((node) => {
          translateNode(node);
          if (node.nodeType === Node.ELEMENT_NODE) {
            walk(node);
            localizeLinks(node);
          }
        });
      });
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true });
  }
}
